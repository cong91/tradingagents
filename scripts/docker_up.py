"""Run the control panel in Docker with a self-generated PostgreSQL password.

The stack needs one secret: the PostgreSQL password. Requiring the operator to
invent and export it before the first ``docker compose up`` is the step people
forget, and a mismatched value shows up as "password authentication failed" in
the API container. This script removes that step:

* first run  - generate a strong password, pick free host ports, write
               ``.env.docker`` (gitignored, 0600) and start the stack;
* later runs - reuse ``.env.docker``, so the password keeps matching the
               PostgreSQL data volume instead of silently rotating.

Usage::

    python scripts/docker_up.py              # build if needed, start, wait for health
    python scripts/docker_up.py --rebuild    # force a clean image rebuild
    python scripts/docker_up.py --status     # container status
    python scripts/docker_up.py --logs       # follow API logs
    python scripts/docker_up.py --down       # stop and remove containers (volumes kept)
    python scripts/docker_up.py --show       # print the connection string
"""

from __future__ import annotations

import argparse
import contextlib
import secrets
import shutil
import socket
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".env.docker"
COMPOSE_FILE = ROOT / "docker-compose.yml"
PROJECT = "tradingagents-local"

# Written on first run only; an existing file is never overwritten, because the
# password has to stay identical to the one inside the PostgreSQL volume.
DEFAULTS = {
    "POSTGRES_DB": "tradingagents",
    "POSTGRES_USER": "tradingagents",
    "TRADINGAGENTS_API_PORT": "8000",
    "TRADINGAGENTS_WEB_PORT": "3000",
    "TRADINGAGENTS_POSTGRES_PORT": "55432",
}


def _read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def _free_port(start: int) -> int:
    """First bindable port at or above ``start`` (loopback probe only)."""
    for port in range(start, start + 200):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
            probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            try:
                probe.bind(("127.0.0.1", port))
            except OSError:
                continue
            return port
    raise RuntimeError(f"no free port found in {start}-{start + 199}")


def _write_env(values: dict[str, str]) -> None:
    lines = [
        "# Generated by scripts/docker_up.py - do not commit.",
        "# The PostgreSQL password below is the only secret in this file; keep it",
        "# stable, because the data volume was initialised with this exact value.",
        "",
    ]
    lines.extend(f"{key}={value}" for key, value in values.items())
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Windows: os.chmod is close to a no-op; the file stays gitignored regardless.
    with contextlib.suppress(OSError):
        ENV_FILE.chmod(0o600)


def ensure_env() -> dict[str, str]:
    """Load or create the compose environment file."""
    existing = _read_env(ENV_FILE)
    if existing.get("POSTGRES_PASSWORD"):
        return existing

    values = dict(DEFAULTS)
    values["TRADINGAGENTS_API_PORT"] = str(_free_port(int(DEFAULTS["TRADINGAGENTS_API_PORT"])))
    values["TRADINGAGENTS_WEB_PORT"] = str(_free_port(int(DEFAULTS["TRADINGAGENTS_WEB_PORT"])))
    values["TRADINGAGENTS_POSTGRES_PORT"] = str(
        _free_port(int(DEFAULTS["TRADINGAGENTS_POSTGRES_PORT"]))
    )
    values["POSTGRES_PASSWORD"] = secrets.token_urlsafe(32)
    _write_env(values)
    print(f"generated {ENV_FILE.name}: new PostgreSQL password, "
          f"api :{values['TRADINGAGENTS_API_PORT']}, web :{values['TRADINGAGENTS_WEB_PORT']}")
    return values


def _compose(args: list[str], env: dict[str, str]) -> int:
    command = [
        "docker", "compose",
        "--env-file", str(ENV_FILE),
        "-f", str(COMPOSE_FILE),
        "-p", PROJECT,
        *args,
    ]
    return subprocess.call(command, cwd=ROOT)


def _require_docker() -> None:
    if shutil.which("docker") is None:
        raise SystemExit("docker is not on PATH; install Docker Desktop first")
    if subprocess.call(
        ["docker", "info", "--format", "{{.ServerVersion}}"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    ) != 0:
        raise SystemExit("the Docker daemon is not running; start Docker Desktop and retry")


def _ensure_app_env() -> None:
    """Compose mounts the repo .env into the API container; create it if absent."""
    app_env = ROOT / ".env"
    if app_env.is_file():
        return
    template = ROOT / ".env.example"
    if template.is_file():
        shutil.copyfile(template, app_env)
        print("created .env from .env.example - add your API keys to enable live analysis")


def main() -> int:
    parser = argparse.ArgumentParser(description="Run the control panel stack with a generated DB password")
    parser.add_argument("--rebuild", action="store_true", help="force a clean image rebuild")
    parser.add_argument("--status", action="store_true", help="show container status")
    parser.add_argument("--logs", action="store_true", help="follow API logs")
    parser.add_argument("--down", action="store_true", help="stop and remove containers (volumes kept)")
    parser.add_argument("--show", action="store_true", help="print the PostgreSQL connection string")
    args = parser.parse_args()

    env = ensure_env()

    if args.show:
        dsn = (
            f"postgresql://{env['POSTGRES_USER']}:{env['POSTGRES_PASSWORD']}"
            f"@127.0.0.1:{env['TRADINGAGENTS_POSTGRES_PORT']}/{env['POSTGRES_DB']}"
        )
        print(dsn)
        return 0

    _require_docker()
    _ensure_app_env()

    if args.down:
        return _compose(["down"], env)
    if args.status:
        return _compose(["ps"], env)
    if args.logs:
        return _compose(["logs", "-f", "api"], env)

    code = _compose(["up", "-d", "--build"] if args.rebuild else ["up", "-d"], env)
    if code != 0:
        return code

    print(f"api : http://127.0.0.1:{env['TRADINGAGENTS_API_PORT']}/api/health")
    print(f"web : http://127.0.0.1:{env['TRADINGAGENTS_WEB_PORT']}")
    print("pass: python scripts/docker_up.py --show")
    return 0


if __name__ == "__main__":
    sys.exit(main())
